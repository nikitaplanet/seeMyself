function starLine(name: string, mutagen?: string): string {
    const mut = mutagen ? `化${mutagen}` : '';
    const trait = STAR_TRAIT[name];
    if (!trait) return `${name}${mut}。`;
    return `${name}${mut}：${trait}。${STAR_DEPTH[name] ?? ''}`;
}

function palaceStarsLine(p: ZiweiPalace, chart: ZiweiChart): string {
    const tip = PALACE_TIP[p.name] ?? '';
    if (p.majorStars.length === 0) {
        const opp = chart.palaces.find((x) => x.index === (p.index + 6) % 12);
        const borrowed = opp?.majorStars.map((s) => s.name) ?? [];
        const head =
            borrowed.length > 0
                ? `主星空宮，傳統上借對宮（${displayPalaceName(opp!.name)}）的${borrowed.join('、')}來參看；這塊性格較有彈性，也較隨其他宮與流年帶動。`
                : '主星空宮，這塊較隨其他宮與流年帶動。';
        return [head, tip].filter(Boolean).join('\n');
    }
    const stars = p.majorStars.map((s) => starLine(s.name, s.mutagen));
    return [...stars, tip].filter(Boolean).join('\n');
}

function palaceField(name: string, extra?: string): string {
    return joinZh([
        PALACE_FIELD[name] ?? `${displayPalaceName(name)}對應人生的一塊領域。`,
        extra ?? '',
    ]);
}

function mutagenPalace(chart: ZiweiChart, star: string): ZiweiPalace | undefined {
    return chart.palaces.find((p) =>
        [...p.majorStars, ...p.minorStars].some((s) => s.name === star),
    );
}

export function ziweiMeaningItems(chart: ZiweiChart): MeaningItem[] {
    const soul = chart.palaces.find((p) => p.isSoulPalace);
    const body = chart.palaces.find((p) => p.isBodyPalace);
    const items: MeaningItem[] = [];

    if (soul) {
        const sameBody = soul.isBodyPalace;
        items.push(
            item(
                displayPalaceName(soul.name, {
                    isSoulPalace: true,
                    isBodyPalace: sameBody,
                }),
                palaceField(soul.name, sameBody ? '身宮同落此宮，身心安放也在這裡。' : ''),
                palaceStarsLine(soul, chart),
            ),
        );
    }
    if (body && body.index !== soul?.index) {
        items.push(
            item(
                displayPalaceName(body.name, { isBodyPalace: true }),
                '身宮落在哪一宮，表示身心安放與人生著力處。',
                palaceStarsLine(body, chart),
            ),
        );
    }

    for (const p of chart.palaces) {
        if (p.isSoulPalace || p.isBodyPalace) continue;
        if (p.majorStars.length === 0) continue;
        items.push(item(displayPalaceName(p.name), palaceField(p.name), palaceStarsLine(p, chart)));
    }

    if (chart.mutagens.length > 0) {
        items.push(
            item(
                '生年四化',
                '落宮主星與祿權科忌，標出該宮較突出的作用。化祿偏順與收穫，化權偏主導，化科偏名聲與文書，化忌偏卡點與在意之處。',
                chart.mutagens
                    .map((m) => {
                        const at = mutagenPalace(chart, m.star);
                        const where = at ? `（落${displayPalaceName(at.name)}）` : '';
                        const note = MUTAGEN_NOTE[m.mutagen] ?? '';
                        return `${m.star}化${m.mutagen}${where}：${note}`;
                    })
                    .join('\n'),
            ),
        );
    }

    return items;
}

