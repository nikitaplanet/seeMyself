/** Channels that carry a cross gate (Sun / Earth, the heaviest activations) come first. */
function rankedChannels(chart: ChartResult): string[] {
    const cross = new Set<number>(chart.cross.gates);
    const ids = chart.channels.map((c) => ({
        id: c.id,
        weight: c.gates.filter((g) => cross.has(g)).length,
    }));
    return ids
        .map((c, i) => ({ ...c, i }))
        .sort((x, y) => y.weight - x.weight || x.i - y.i)
        .map((c) => c.id);
}

function channelName(id: string): string {
    const name = CHANNEL_NAMES_ZH[id];
    return name ? `${id} ${name}` : id;
}

