type Pair = 'dd' | 'do' | 'od' | 'oo';

function pairKey(first: boolean, second: boolean): Pair {
    return `${first ? 'd' : 'o'}${second ? 'd' : 'o'}` as Pair;
}

function state(defined: boolean): string {
    return defined ? '有定義' : '開放';
}

