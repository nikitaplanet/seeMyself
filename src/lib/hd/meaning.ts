export function formatHdCard(c: HdCard): string {
    return [
        '【解析】',
        ...c.insight,
        '【生活場景】',
        c.scene,
        '【給你的建議】',
        c.advice,
        `（依據：${c.basis}）`,
    ].join('\n');
}

/** Theme cards first, then the term-by-term reference (folded). */
export function hdMeaningItems(chart: ChartResult): MeaningItem[] {
    return [
        ...hdThemeCards(chart).map((c) => ({
            term: c.term,
            field: c.field,
            hook: c.hook,
            meaning: formatHdCard(c),
        })),
        ...hdReferenceItems(chart),
    ];
}
