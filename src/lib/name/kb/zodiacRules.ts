// 生肖喜忌字根對照庫（spec §2C）。字根一律用完整部件字（艸、水、心、手、犬、玉、肉…）。
// 每條規則附一個簡短理由（顯示在卡片標籤），並歸入一個心理轉譯類別（ROOT_EFFECTS）。
// 各家說法不一致的字根（例如鼠與肉、馬與宀、猴與木）不收，只收多數來源一致的部分。

export type LikeCategory = 'food' | 'den' | 'ally' | 'crown' | 'terrain' | 'boost';
export type AvoidCategory =
    'clash' | 'harm' | 'nofood' | 'trapped' | 'exposed' | 'sacrifice' | 'demote' | 'gossip';
export type RootCategory = LikeCategory | AvoidCategory;

export interface ZodiacRootRule {
    root: string;
    kind: 'like' | 'avoid';
    category: RootCategory;
    /** 簡短理由，例如「寅午戌三合」「草食得食」。 */
    reason: string;
    /** 影響強度 1–3：沖、合、本命食物最強，泛用的五行或人字旁最弱。 */
    strength: 1 | 2 | 3;
}

export interface ZodiacRule {
    zodiac: Zodiac;
    like: ZodiacRootRule[];
    avoid: ZodiacRootRule[];
}

