type Spec = [roots: string[], category: RootCategory, reason: string, strength: 1 | 2 | 3];

const build = (kind: 'like' | 'avoid', specs: Spec[]): ZodiacRootRule[] => {
    const seen = new Set<string>();
    const out: ZodiacRootRule[] = [];
    for (const [roots, category, reason, strength] of specs)
        for (const root of roots) {
            if (seen.has(root)) continue;
            seen.add(root);
            out.push({ root, kind, category, reason, strength });
        }
    return out;
};

const rule = (zodiac: Zodiac, like: Spec[], avoid: Spec[]): ZodiacRule => ({
    zodiac,
    like: build('like', like),
    avoid: build('avoid', avoid),
});

