const BY_ZODIAC = new Map(ZODIAC_RULES.map((r) => [r.zodiac, r]));

export function zodiacRule(z: Zodiac): ZodiacRule {
    return BY_ZODIAC.get(z) as ZodiacRule;
}

/** 這個生肖對某字根的喜忌；同一字根同時列在喜、忌時取強度高者，強度相同取喜用。 */
export function matchRoot(z: Zodiac, root: string): ZodiacRootRule | undefined {
    const r = zodiacRule(z);
    const like = r.like.find((x) => x.root === root);
    const avoid = r.avoid.find((x) => x.root === root);
    if (like && avoid) return avoid.strength > like.strength ? avoid : like;
    return like ?? avoid;
}

/** 知識庫用到的所有字根（供和字典的 roots.json 比對）。 */
export function allRuleRoots(): string[] {
    const s = new Set<string>();
    for (const r of ZODIAC_RULES) for (const x of [...r.like, ...r.avoid]) s.add(x.root);
    return [...s].sort();
}

