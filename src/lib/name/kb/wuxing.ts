import type { Wuxing } from '../types';

// 五行的現代心理轉譯：思考方式（依數的陰陽分兩型）、金錢觀、各領域備用盲點與建議。
// 子句（think／money／spend…）省略主詞、不含「你」；shadow 類是完整句子。

export type Polarity = 'yang' | 'yin';
export type Relation = 'same' | 'gen' | 'genBy' | 'ctl' | 'ctlBy';

const ORDER: Wuxing[] = ['木', '火', '土', '金', '水'];

/** from 對 to 的關係：same 比和、gen 我生、genBy 生我、ctl 我剋、ctlBy 剋我。 */
export function relation(from: Wuxing, to: Wuxing): Relation {
    const d = (ORDER.indexOf(to) - ORDER.indexOf(from) + 5) % 5;
    return (['same', 'gen', 'ctl', 'ctlBy', 'genBy'] as const)[d];
}

export const isHarmony = (r: Relation) => r === 'same' || r === 'gen' || r === 'genBy';

export const RELATION_TAG: Record<Relation, (a: Wuxing, b: Wuxing) => string> = {
    same: (a) => `${a}${a}比和`,
    gen: (a, b) => `${a}生${b}`,
    genBy: (a, b) => `${b}生${a}`,
    ctl: (a, b) => `${a}剋${b}張力`,
    ctlBy: (a, b) => `${b}剋${a}張力`,
};

/** 奇數為陽、偶數為陰（1 陽木、2 陰木…9 陽水、0 陰水）。 */
export const polarity = (n: number): Polarity => (n % 2 === 1 ? 'yang' : 'yin');

