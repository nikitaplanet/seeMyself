// 125 種三才組合的傳統判讀（吉→a、半吉→m、凶→c），順序為 天×人×地，各依 木火土金水。
const ELEMENTS: Wuxing[] = ['木', '火', '土', '金', '水'];
const COMBO_TABLE = [
    'aaacc amacc cmmmc ccccc accaa', // 木＿＿
    'aaacc amacc caaac ccmcc ccccc', // 火＿＿
    'mmccc aaacc caaac ccaaa ccccc', // 土＿＿
    'ccccc ccccc caaac ccacm accam', // 金＿＿
    'aaacm ccccc cmmmc ccaac mccmc', // 水＿＿
]
    .join('')
    .replace(/ /g, '');

export type SancaiPattern =
    'chainDown' | 'chainUp' | 'allSame' | 'squeezed' | 'pushing' | 'supported' | 'giving' | 'plain';

/** 三才的結構型態：只有傳統上另有專門判讀的型態才有名字，其餘歸 plain。 */
export function sancaiPattern([tian, ren, di]: [Wuxing, Wuxing, Wuxing]): SancaiPattern {
    const up = relation(ren, tian);
    const down = relation(ren, di);
    if (up === 'same' && down === 'same') return 'allSame';
    if (up === 'genBy' && down === 'gen') return 'chainDown';
    if (up === 'gen' && down === 'genBy') return 'chainUp';
    if (up === 'ctlBy' && down === 'ctlBy') return 'squeezed';
    if (up === 'ctl' && down === 'ctl') return 'pushing';
    if (up === 'genBy' && down === 'genBy') return 'supported';
    if (up === 'gen' && down === 'gen') return 'giving';
    return 'plain';
}

export interface SancaiCombo {
    number_or_pattern: string;
    energy_type: EnergyType;
    pattern: SancaiPattern;
}

const COMBO_ENERGY = { a: 'auspicious', m: 'mixed', c: 'challenging' } as const;

export const SANCAI_COMBOS: Record<string, SancaiCombo> = (() => {
    const out: Record<string, SancaiCombo> = {};
    let i = 0;
    for (const t of ELEMENTS)
        for (const r of ELEMENTS)
            for (const d of ELEMENTS) {
                const key = `${t}${r}${d}`;
                out[key] = {
                    number_or_pattern: key,
                    energy_type: COMBO_ENERGY[COMBO_TABLE[i++] as 'a' | 'm' | 'c'],
                    pattern: sancaiPattern([t, r, d]),
                };
            }
    return out;
})();

