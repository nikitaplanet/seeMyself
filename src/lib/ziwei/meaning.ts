interface MutagenAt {
    star: string;
    palace: ZiweiPalace | undefined;
    /** 「（武曲化祿在財帛宮）」 */
    basis: string;
}

function mutagenAt(chart: ZiweiChart, mutagen: string): MutagenAt | undefined {
    const m = chart.mutagens.find((x) => x.mutagen === mutagen);
    if (!m) return undefined;
    const palace = chart.palaces.find((p) =>
        [...p.majorStars, ...p.minorStars].some((s) => s.name === m.star),
    );
    return {
        star: m.star,
        palace,
        basis: `（${m.star}化${mutagen}${palace ? `在${displayPalaceName(palace.name)}` : ''}）`,
    };
}

