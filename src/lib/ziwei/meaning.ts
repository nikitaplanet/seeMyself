export interface PalaceStars {
    names: string[];
    borrowed: boolean;
}

/** 某宮的主星；空宮借對宮主星。 */
export function starsOfPalace(
    chart: ZiweiChart,
    palace: ZiweiPalace | undefined | null,
): PalaceStars {
    if (!palace) return { names: [], borrowed: false };
    if (palace.majorStars.length > 0)
        return { names: palace.majorStars.map((s) => s.name), borrowed: false };
    const opp = chart.palaces.find((p) => p.index === (palace.index + 6) % 12);
    return { names: opp?.majorStars.map((s) => s.name) ?? [], borrowed: true };
}

export function palaceByName(chart: ZiweiChart, name: string): ZiweiPalace | undefined {
    if (name === '命宮')
        return chart.palaces.find((p) => p.isSoulPalace) ?? chart.palaces.find((p) => p.name === name);
    return chart.palaces.find((p) => p.name === name);
}

/** 第一顆有資料的主星（雙星宮以排在前面的星為主）。 */
export function leadOf<T>(ps: PalaceStars, table: Record<string, T>): T | undefined {
    for (const n of ps.names) if (table[n] !== undefined) return table[n];
    return undefined;
}

/** 「（命宮紫微、天府）」「（夫妻宮借對宮天機）」 */
export function basisOf(label: string, ps: PalaceStars): string {
    if (ps.names.length === 0) return `（${label}無主星）`;
    return `（${label}${ps.borrowed ? '借對宮' : ''}${ps.names.join('、')}）`;
}

/** 把依據放進句尾的句號之前。 */
export function withBasis(text: string, basis: string): string {
    if (!basis) return text;
    return text.endsWith('。') ? `${text.slice(0, -1)}${basis}。` : `${text}${basis}`;
}

